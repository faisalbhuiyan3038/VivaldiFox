await waitFor(() => $("#vfx-sessions"), "widget");
const { Sessions } = win.vfxSessions;
const u1 = web("<title>S1</title>1"), u2 = web("<title>S2</title>2");
await openTab(u1); await openTab(u2);
const s = await Sessions.save(win, "Test session");
assert(s && s.tabs.length === 2 && s.tabs[0].url === u1 && s.tabs[1].title === "S2", "saved 2 real tabs, skipped about:blank: " + JSON.stringify(s?.tabs.map(t => t.title)));
const disk = await IOUtils.readJSON(PathUtils.join(PathUtils.profileDir, "vivaldifox-data", "sessions.json"));
assert(disk.list.some(x => x.id === s.id), "persisted");
const n = gBrowser.tabs.length;
Sessions.open(win, s, "here");
await waitFor(() => gBrowser.tabs.length === n + 2, "reopened in this window");
const count = () => [...Services.wm.getEnumerator("navigator:browser")].length;
const c0 = count();
Sessions.open(win, s, "window");
const nw = await waitFor(() => count() === c0 + 1 && [...Services.wm.getEnumerator("navigator:browser")].find(w => w !== win && w.gBrowser?.tabs.length === 2), "new window with the session's 2 tabs", 15000);
await waitFor(() => nw.gBrowser.tabs.every(t => /127\.0\.0\.1/.test(t.linkedBrowser.currentURI.spec)), "session addresses loaded");
nw.close(); await waitFor(() => count() === c0, "closed");
await Sessions.remove(s.id);
assert(!(await Sessions.list()).some(x => x.id === s.id), "deleted");
return "session saved to disk, reopened here and in a new window, deleted";
