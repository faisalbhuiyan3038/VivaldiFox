const { ReadingList } = win.vfxReadingList;
const url = web("<title>Read me later</title>rl");
const t = await openTab(url); gBrowser.selectedTab = t;
const item = await win.vfxReadingList.addCurrent();
assert(item?.guid, "added");
const bm = await win.PlacesUtils.bookmarks.fetch(item.guid);
const parent = await win.PlacesUtils.bookmarks.fetch(bm.parentGuid);
assert(parent.title === "Reading List", "stored as a bookmark in the Reading List folder");
$('.vfx-panel-btn[data-panel="readingList"]').doCommand();
const node = await waitFor(() => $('.vfx-panel[data-panel="readingList"]'), "panel built");
const row = await waitFor(() => node.querySelector('.vfx-rl-row[data-guid="' + item.guid + '"]'), "row shown");
assert(row.querySelector(".vfx-p-title").textContent === "Read me later", "title");
await ReadingList.setRead(item.guid, true);
await waitFor(() => node.querySelector('.vfx-rl-row[data-guid="' + item.guid + '"]')?.hasAttribute("vfx-read"), "marked read");
await ReadingList.remove(item.guid);
await waitFor(() => !node.querySelector('.vfx-rl-row[data-guid="' + item.guid + '"]'), "removed");
await win.PlacesUtils.bookmarks.remove(parent.guid).catch(() => {});
$("#vfx-toast")?.remove();
return "page saved as bookmark in 'Reading List', listed, marked read, removed";
